#!/usr/bin/env bash
# RaceDay Part 3: start SQL Server in Codespaces and apply SQL Server migrations.
# Does not change the original Windows LocalDB settings in the API source.
set -euo pipefail
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PART3="$REPO_ROOT/Raceday part 3"
ENV_FILE="$REPO_ROOT/.raceday-codespaces.env"
cd "$REPO_ROOT"

for program in dotnet docker openssl; do
  if ! command -v "$program" >/dev/null 2>&1; then
    echo "ERROR: $program is not installed in this environment." >&2
    exit 1
  fi
done
if ! docker info >/dev/null 2>&1; then
  echo "ERROR: Docker daemon is unavailable. This Codespace must support Docker." >&2
  exit 1
fi
if [[ ! -f "$ENV_FILE" ]]; then
  umask 077
  # Guaranteed upper/lower/digit/symbol; suitable for SQL Server's password policy.
  DB_PASSWORD="Ra!1$(openssl rand -hex 18)Z"
  printf 'MSSQL_SA_PASSWORD=%s\n' "$DB_PASSWORD" > "$ENV_FILE"
  chmod 600 "$ENV_FILE"
  unset DB_PASSWORD
fi
# The environment file is generated by this script and is deliberately gitignored.
# shellcheck disable=SC1090
source "$ENV_FILE"
if [[ -z "${MSSQL_SA_PASSWORD:-}" ]]; then
  echo "ERROR: MSSQL_SA_PASSWORD is absent from the local env file." >&2
  exit 1
fi

CONTAINER_NAME='raceday-part3-sql'
if docker container inspect "$CONTAINER_NAME" >/dev/null 2>&1; then
  echo 'Starting existing SQL Server container...'
  docker start "$CONTAINER_NAME" >/dev/null
else
  echo 'Creating private SQL Server container and persistent database volume...'
  docker run -d \
    --name "$CONTAINER_NAME" \
    --restart unless-stopped \
    -e ACCEPT_EULA=Y \
    -e "MSSQL_SA_PASSWORD=$MSSQL_SA_PASSWORD" \
    -p 127.0.0.1:1433:1433 \
    -v raceday-part3-sql-data:/var/opt/mssql \
    mcr.microsoft.com/mssql/server:2022-latest >/dev/null
fi

export ConnectionStrings__RaceDayConnection="Server=127.0.0.1,1433;Database=RaceDayPart3DB;User Id=sa;Password=${MSSQL_SA_PASSWORD};Encrypt=True;TrustServerCertificate=True;MultipleActiveResultSets=true"
export ASPNETCORE_ENVIRONMENT=Development

if ! dotnet tool list --global | grep -Eq '^dotnet-ef[[:space:]]'; then
  echo 'Installing the EF Core 8 CLI tool...'
  dotnet tool install --global dotnet-ef --version 8.0.11
fi
export PATH="$HOME/.dotnet/tools:$PATH"

# The SQL Server process can accept TCP before the database engine is ready;
# retries avoid this transient boot-up error.
echo 'Applying existing RaceDay SQL Server migrations...'
ready=0
for attempt in $(seq 1 30); do
  if dotnet ef database update --project "$PART3/Raceday.API.csproj" --startup-project "$PART3/Raceday.API.csproj"; then
    ready=1
    break
  fi
  echo "Database not ready (attempt $attempt of 30). Retrying..."
  sleep 5
done
if [[ "$ready" -ne 1 ]]; then
  echo 'ERROR: Database migration failed. Check: docker logs raceday-part3-sql' >&2
  exit 1
fi
echo
echo 'Database ready. In TWO separate terminals run:'
echo '  bash scripts/run-api.sh'
echo '  bash scripts/run-web.sh'
echo 'Then in a third terminal run:'
echo '  python3 scripts/smoke-test.py'
